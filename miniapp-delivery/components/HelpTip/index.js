/**
 * 「?」解释按钮（2026-09-24 新建）。
 *
 * 起因（产品原话）：「现在的界面好啰嗦，每一项都详细解释，加一个问号藏在里面怎么样」。
 * 此前大量页面在字段/卡片下面平铺一整句说明（`card-sub` / `hint` / `tip` / `card-desc`…），
 * 一个配置页能堆 5 段，站长真正要看的字段反而被挤没了。
 *
 * 用法：把原来那行 `<text class="card-sub">长说明</text>` 换成
 *     <help-tip text="长说明" />
 * 放在**卡片标题右边**最自然；`title` 不传就用「说明」。
 * 已在本端 `app.json` 的全局 `usingComponents` 注册，页面无需再声明（同 privacy-popup）。
 *
 * ⚠️ 三条边界，改之前先读：
 *   1. **藏的是"概念与解释"，不是"当前发生了什么"**（2026-09-24 产品口径："只藏概念、解释这种东西"）。
 *      可以藏：这个字段是什么意思、这条规则怎么算、为什么需要它、系统内部谁算的。
 *      不许藏 —— 下面四类**必须保持可见**：
 *      ① **当前状态与阻断理由**（"水桶正在配送中，请饮完再下单"、"该商品欠桶 2 个，需先归还才能退押金"）；
 *      ② **报错与排障**（"没拉到数据，下拉刷新重试"）；
 *      ③ **关系到当事人钱的短激励**（"填了才算楼层补贴"—— 藏了配送员会跳过不填 = 少拿钱）；
 *      ④ 数据行（"送桶 ¥3 · 楼层 ¥2/层"）—— 那些根本不是解释。
 *      判据：**藏起来会不会让人做出错的决定？会，就别藏。**
 *      （产品 2026-09-24 明确：坐标这类"配置原理"算概念，**可以藏**，已并进「配送范围 ?」。）
 *   2. 展开用的是 `wx.showModal`，**不是**自绘浮层：这里只放一段纯文字，不需要列表/跳转，
 *      用系统弹窗最省事且不会被页面层级盖住（营业状态小框那种要放可点列表的才必须自绘）。
 *   3. ⚠️ `catchtap`：本组件常被放进**整行可点**的容器里（卡片头、列表行），
 *      用 `bindtap` 会冒泡出去把用户带到别的页面。
 *   4. ⚠️ `text` 属性**只接一个数据字段或字面量**。要拼多段（如 why + suggestion）必须在
 *      **页面的 js 里拼好**再传 —— 别写 `text="{{a}}{{b ? '\n\n' + b : ''}}"`，
 *      WXML 表达式解析器吃不下带换行的拼接，会**直接编译报错**（Bad attr，2026-09-24 实测，
 *      且本地没有任何门禁能发现）。详见 AGENTS §6「小程序」那条。
 */
Component({
  properties: {
    /** 说明正文。支持多段：用 \n 分段，showModal 会原样换行。 */
    text: {
      type: String,
      value: ''
    },
    /** 弹窗标题。默认「说明」，一般传字段名/卡片名更有用。 */
    title: {
      type: String,
      value: '说明'
    }
  },

  methods: {
    onTap() {
      const text = (this.data.text || '').trim()
      // 没内容就什么都不做：宁可点了没反应，也不要弹一个空框
      if (!text) return
      wx.showModal({
        title: this.data.title || '说明',
        content: text,
        showCancel: false,
        confirmText: '知道了'
      })
    }
  }
})
